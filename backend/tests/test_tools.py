@pytest.fixture(autouse=True)
def start_menu(monkeypatch):
    """Every test here sees the made-up Start Menu, never the real one.

    Add to `.entries` to install something; `.reads` counts how often she looked.
    """
    menu = types.SimpleNamespace(entries=list(START_MENU), reads=0)

