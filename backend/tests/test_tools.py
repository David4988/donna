def test_installed_apps_reads_utf8(monkeypatch):
    """Windows PowerShell's default code page would make "HWiNFO® 64" "HWiNFO? 64"."""
    out = json.dumps([{"Name": "HWiNFO® 64", "AppID": "H64"}], ensure_ascii=False).encode("utf-8")

    def run(args, **kwargs):
        assert args[0] == "powershell" and "UTF8" in args[-1]
        assert "shell" not in kwargs
        return subprocess.CompletedProcess(args, 0, stdout=out, stderr=b"")

    monkeypatch.setattr(subprocess, "run", run)
    assert REAL_INSTALLED_APPS() == {"HWiNFO® 64": "H64"}


